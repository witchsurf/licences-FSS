-- Persist the club catalogue independently from licenses, so a custom club
-- remains available in future dropdowns.
CREATE TABLE IF NOT EXISTS clubs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) > 0),
  normalized_name text NOT NULL UNIQUE,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE clubs ENABLE ROW LEVEL SECURITY;

-- The API uses the service role and bypasses RLS. This policy keeps the
-- catalogue readable if a public client needs it later.
CREATE POLICY "Public Read Access" ON clubs
  FOR SELECT USING (true);

