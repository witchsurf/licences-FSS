INSERT INTO clubs (name, normalized_name)
SELECT DISTINCT ON (normalized_name) name, normalized_name
FROM (
  SELECT
    CASE
      WHEN upper(trim(club)) = 'TAKEOFF NGOR' THEN 'TAKE OFF NGOR'
      ELSE trim(club)
    END AS name,
    CASE
      WHEN upper(trim(club)) = 'TAKEOFF NGOR' THEN 'TAKE OFF NGOR'
      ELSE upper(trim(club))
    END AS normalized_name
  FROM licenses
  WHERE club IS NOT NULL AND trim(club) <> ''
) license_clubs
ON CONFLICT (normalized_name) DO NOTHING;
